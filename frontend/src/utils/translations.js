export const getTranslation = (language, key) => {
  if (!language || !key) return key;
  const keys = key.split('.');
  let value = translations[language] || translations['English'];
  
  if (!value) return key;
  
  for (const k of keys) {
    if (value[k] === undefined) {
      // Fallback to English if translation is missing
      let engValue = translations['English'];
      for (const engK of keys) {
        if (engValue === undefined) return key;
        engValue = engValue[engK];
      }
      return engValue || key;
    }
    value = value[k];
  }
  return value || key;
};
